/**
 * Regenerates src/lib/postal-states.ts, the table that maps a German postal
 * code to its state, from OpenPLZ API (https://www.openplzapi.org, open data
 * from the federal and state statistics offices). Postal codes rarely change,
 * so run this by hand once a year or so:
 *
 *   bun scripts/postal-states.ts
 */
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { states } from "../src/lib/medicine.ts";
import { getJson } from "./fetchers/http.ts";

const API = "https://openplzapi.org/de";
const PAGE_SIZE = 50;
const OUT = join(import.meta.dirname, "..", "src", "lib", "postal-states.ts");

interface FederalState {
  key: string;
  name: string;
}

interface Locality {
  postalCode: string;
}

/** Every postal code in one state, read page by page. */
async function postalCodes(stateKey: string): Promise<string[]> {
  const codes: string[] = [];
  for (let page = 1; ; page++) {
    const list = await getJson<Locality[]>(`${API}/FederalStates/${stateKey}/Localities?page=${page}&pageSize=${PAGE_SIZE}`);
    codes.push(...list.map((l) => l.postalCode));
    if (list.length < PAGE_SIZE) return codes;
  }
}

/**
 * Collapses code → state into runs: each run starts at a code and holds until
 * the next run, so the gaps between codes go to the state before them. A code
 * that two states share (a few border towns) goes to the state with more
 * localities under it.
 */
export function toRuns(byState: Map<number, string[]>): [number, number][] {
  const votes = new Map<number, Map<number, number>>();
  for (const [state, codes] of byState) {
    for (const code of codes) {
      const n = Number(code);
      const tally = votes.get(n) ?? new Map<number, number>();
      tally.set(state, (tally.get(state) ?? 0) + 1);
      votes.set(n, tally);
    }
  }
  const runs: [number, number][] = [];
  for (const code of [...votes.keys()].sort((a, b) => a - b)) {
    const [state] = [...votes.get(code)!].sort((a, b) => b[1] - a[1] || a[0] - b[0])[0]!;
    if (runs.at(-1)?.[1] !== state) runs.push([code, state]);
  }
  return runs;
}

async function main() {
  const federal = await getJson<FederalState[]>(`${API}/FederalStates`);
  const byState = new Map<number, string[]>();
  for (const f of federal) {
    const index = states.findIndex((s) => s.name === f.name.split(",")[0]);
    if (index < 0) throw new Error(`no state named "${f.name}" in src/lib/medicine.ts`);
    byState.set(index, await postalCodes(f.key));
    console.log(`${f.name}: ${byState.get(index)!.length} localities`);
  }
  const runs = toRuns(byState);
  const body = runs.map(([code, state]) => `[${code},${state}]`).join(",");
  await writeFile(
    OUT,
    `// Generated by scripts/postal-states.ts from OpenPLZ API (open data); do not edit by hand.\n` +
      `// Runs of [first postal code, index into \`states\` in medicine.ts], sorted by code.\n` +
      `export const postalRuns: readonly (readonly [number, number])[] = [${body}];\n`,
  );
  console.log(`wrote ${runs.length} runs to ${OUT}`);
}

if (import.meta.main) await main();
