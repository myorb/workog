/**
 * Regenerates src/lib/nuts-names.ts, the names of the EU's NUTS regions, from
 * Eurostat's GISCO open data. EURES gives a job's region as a NUTS code
 * ("fri22") when it names no city. NUTS changes every few years, so run this
 * by hand when Eurostat publishes a new version:
 *
 *   bun scripts/nuts-names.ts
 */
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { getText } from "./fetchers/http.ts";

const VERSION = "2021";
const CSV = `https://gisco-services.ec.europa.eu/distribution/v2/nuts/csv/NUTS_AT_${VERSION}.csv`;
const OUT = join(import.meta.dirname, "..", "src", "lib", "nuts-names.ts");
/** countries EURES covers that we list; Germany comes from the Arbeitsagentur, the UK left EURES */
const SKIP = new Set(["DE", "UK", "TR", "AL", "ME", "MK", "RS"]);

/** "FR,FRI22,Creuse,Creuse,4,3,3" → code and Latin-script name; names with commas are quoted. */
export function parseNutsCsv(csv: string): [string, string][] {
  const rows: [string, string][] = [];
  for (const line of csv.split(/\r?\n/).slice(1)) {
    const cells = [...line.matchAll(/("([^"]*(?:""[^"]*)*)"|[^,]*)(,|$)/g)].map((m) => (m[2] ?? m[1] ?? "").replace(/""/g, '"'));
    const [country, id, name] = cells;
    if (!country || !id || !name || SKIP.has(country)) continue;
    rows.push([id.toLowerCase(), name.trim()]);
  }
  return rows.sort((a, b) => a[0].localeCompare(b[0]));
}

async function main() {
  const rows = parseNutsCsv(await getText(CSV));
  const body = rows.map(([id, name]) => `  ${JSON.stringify(id)}: ${JSON.stringify(name)},`).join("\n");
  await writeFile(
    OUT,
    `// Generated by scripts/nuts-names.ts from Eurostat GISCO (NUTS ${VERSION}, open data); do not edit by hand.\n` +
      `// NUTS code (lower case, as EURES writes it) → region name in Latin script.\n` +
      `export const nutsNames: Readonly<Record<string, string>> = {\n${body}\n};\n`,
  );
  console.log(`wrote ${rows.length} regions to ${OUT}`);
}

if (import.meta.main) await main();
